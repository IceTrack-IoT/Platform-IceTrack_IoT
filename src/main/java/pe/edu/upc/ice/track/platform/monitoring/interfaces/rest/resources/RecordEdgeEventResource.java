package pe.edu.upc.ice.track.platform.monitoring.interfaces.rest.resources;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.DecimalMax;
import jakarta.validation.constraints.DecimalMin;
import jakarta.validation.constraints.NotNull;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * Resource received from an edge gateway reporting a thermal excursion event.
 *
 * <p>The device and the unit come from the API key; {@code equipment_id} and {@code device_id} are
 * optional and, when sent, must match it.</p>
 */
@Schema(
    name = "RecordEdgeEventRequest",
    description = "Event detected by an edge gateway",
    example = "{\"event_uid\": \"6f1c2d34-8a7b-4c1e-9f00-1a2b3c4d5e6f\", \"type\": \"THERMAL_EXCURSION_DETECTED\", "
        + "\"occurred_at\": \"2026-11-07T08:32:00\", \"temperature_celsius\": 9.5, "
        + "\"reading_uid\": \"3fa85f64-5717-4562-b3fc-2c963f66afa6\"}")
public record RecordEdgeEventResource(
    @NotNull(message = "{validation.not-null}")
    @Schema(description = "Identifier generated by the gateway; retries must reuse it",
        example = "6f1c2d34-8a7b-4c1e-9f00-1a2b3c4d5e6f", requiredMode = Schema.RequiredMode.REQUIRED)
    UUID eventUid,

    @NotNull(message = "{validation.not-null}")
    @Schema(description = "Kind of event", example = "THERMAL_EXCURSION_DETECTED",
        requiredMode = Schema.RequiredMode.REQUIRED)
    EdgeEventTypeResource type,

    @NotNull(message = "{validation.not-null}")
    @Schema(description = "When the gateway observed the event, by its clock", example = "2026-11-07T08:32:00",
        requiredMode = Schema.RequiredMode.REQUIRED)
    LocalDateTime occurredAt,

    @DecimalMin(value = "-50.0", message = "{validation.edge-event.temperature}")
    @DecimalMax(value = "60.0", message = "{validation.edge-event.temperature}")
    @Schema(description = "Out-of-range temperature, in Celsius; required for THERMAL_EXCURSION_DETECTED",
        example = "9.5", nullable = true)
    Double temperatureCelsius,

    @DecimalMin(value = "-50.0", message = "{validation.edge-event.temperature}")
    @DecimalMax(value = "60.0", message = "{validation.edge-event.temperature}")
    @Schema(description = "Most extreme temperature of the excursion, in Celsius; optional with "
        + "THERMAL_EXCURSION_NORMALIZED", example = "10.5", nullable = true)
    Double peakTemperatureCelsius,

    @Schema(description = "reading_uid of the batch the excursion was detected in, recorded as the triggering "
        + "reading when that batch is stored", example = "3fa85f64-5717-4562-b3fc-2c963f66afa6", nullable = true)
    UUID readingUid,

    @Schema(description = "Optional; must match the unit the API key is paired with", example = "10", nullable = true)
    Long equipmentId,

    @Schema(description = "Optional; must match the device the API key belongs to", example = "7", nullable = true)
    Long deviceId
) {
}
