package pe.edu.upc.ice.track.platform.monitoring.interfaces.rest.resources;

import io.swagger.v3.oas.annotations.media.Schema;

import java.time.Instant;
import java.util.UUID;

/**
 * Outbound REST resource acknowledging an edge event and telling what it did.
 */
@Schema(
    name = "EdgeEventResponse",
    description = "Processed edge event",
    example = "{\"event_uid\": \"6f1c2d34-8a7b-4c1e-9f00-1a2b3c4d5e6f\", \"type\": \"THERMAL_EXCURSION_DETECTED\", "
        + "\"occurred_at\": \"2026-11-07T08:32:00Z\", \"result\": \"ALERT_OPENED\", \"alert_id\": 301, "
        + "\"maintenance_window_id\": null}")
public record EdgeEventResource(
    @Schema(description = "Identifier generated by the gateway", example = "6f1c2d34-8a7b-4c1e-9f00-1a2b3c4d5e6f")
    UUID eventUid,

    @Schema(description = "Kind of event", example = "THERMAL_EXCURSION_DETECTED",
        allowableValues = {"THERMAL_EXCURSION_DETECTED", "THERMAL_EXCURSION_NORMALIZED",
            "MAINTENANCE_WINDOW_STARTED", "MAINTENANCE_WINDOW_ENDED"})
    String type,

    @Schema(description = "When the gateway observed the event", example = "2026-11-07T08:32:00Z")
    Instant occurredAt,

    @Schema(description = "What processing the event did", example = "ALERT_OPENED",
        allowableValues = {"ALERT_OPENED", "ALERT_ALREADY_ACTIVE", "ALERT_RESOLVED", "NO_ACTIVE_ALERT",
            "SUPPRESSED_BY_MAINTENANCE", "MAINTENANCE_WINDOW_OPENED", "MAINTENANCE_WINDOW_PROMOTED",
            "MAINTENANCE_ALREADY_ACTIVE", "MAINTENANCE_WINDOW_CLOSED", "NO_ACTIVE_MAINTENANCE"})
    String result,

    @Schema(description = "Alert opened, already active or resolved; null otherwise", example = "301",
        nullable = true)
    Long alertId,

    @Schema(description = "Maintenance window opened, kept, promoted or closed, or the one covering a suppressed "
        + "detection; null otherwise", example = "18", nullable = true)
    Long maintenanceWindowId
) {
}
