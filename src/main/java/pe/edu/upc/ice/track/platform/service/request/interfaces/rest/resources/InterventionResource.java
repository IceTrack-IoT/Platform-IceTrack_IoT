package pe.edu.upc.ice.track.platform.service.request.interfaces.rest.resources;

import io.swagger.v3.oas.annotations.media.Schema;

import java.util.List;
import java.util.UUID;

/**
 * Outbound REST resource representing the intervention that completed a service request.
 */
@Schema(
    name = "InterventionResponse",
    description = "Technical report of the work that completed a service request",
    example = "{\"service_request_id\": 42, \"client_generated_id\": \"3f2b8c1e-6a4d-4e0b-9a51-2c7d8e9f0a1b\", "
        + "\"technician_id\": 7, \"equipment_id\": 10, \"diagnosis\": \"Compressor relay burnt\", "
        + "\"actions_taken\": \"Replaced the start relay and tested the cycle\", \"spare_parts\": [\"Start relay 4TM\"], "
        + "\"photo_evidence\": [\"https://cdn.example.com/photos/42-1.jpg\"], \"started_at\": \"2026-10-23T14:05:00Z\", "
        + "\"completed_at\": \"2026-10-23T16:30:00Z\", \"duration_seconds\": 8700}")
public record InterventionResource(
    @Schema(description = "Identifier of the service request the intervention completed", example = "42")
    Long serviceRequestId,

    @Schema(description = "UUID generated by the technician's device", example = "3f2b8c1e-6a4d-4e0b-9a51-2c7d8e9f0a1b")
    UUID clientGeneratedId,

    @Schema(description = "Technician who performed the work", example = "7")
    Long technicianId,

    @Schema(description = "Unit the work was performed on", example = "10")
    Long equipmentId,

    @Schema(description = "What the technician found", example = "Compressor relay burnt")
    String diagnosis,

    @Schema(description = "What the technician did", example = "Replaced the start relay and tested the cycle")
    String actionsTaken,

    @Schema(description = "Spare parts used")
    List<String> spareParts,

    @Schema(description = "References of the photos taken")
    List<String> photoEvidence,

    @Schema(description = "When the work started, ISO-8601 UTC", example = "2026-10-23T14:05:00Z")
    String startedAt,

    @Schema(description = "When the work finished, ISO-8601 UTC", example = "2026-10-23T16:30:00Z")
    String completedAt,

    @Schema(description = "How long the work took, in seconds", example = "8700")
    Long durationSeconds
) {
}
